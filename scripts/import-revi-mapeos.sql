UPDATE mapeo_producto_ps m
SET productoId = (SELECT id FROM producto WHERE referencia = m.referencia LIMIT 1)
WHERE m.productoId IS NULL AND EXISTS (SELECT 1 FROM producto WHERE referencia = m.referencia);

